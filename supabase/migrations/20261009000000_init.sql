create table if not exists public.users (
  id            integer generated by default as identity primary key,
  username      varchar(50)  not null unique,
  email         varchar(100) not null unique,
  password_hash varchar(255) not null,
  role          text         not null check (role in ('client', 'freelancer')),
  created_at    timestamp    not null default now()
);

create table if not exists public.freelancers (
  id         integer generated by default as identity primary key,
  user_id    integer      not null references public.users (id) on delete cascade,
  firstname  varchar(100) not null,
  middlename varchar(100),
  lastname   varchar(100) not null,
  phone      varchar(20),
  dob        date,
  address    text,
  created_at timestamp    not null default now()
);

create table if not exists public.individual_clients (
  id         integer generated by default as identity primary key,
  user_id    integer      not null references public.users (id) on delete cascade,
  firstname  varchar(100) not null,
  middlename varchar(100),
  lastname   varchar(100) not null,
  phone      varchar(20),
  dob        date,
  address    text,
  created_at timestamp    not null default now()
);

create table if not exists public.businesses (
  id            integer generated by default as identity primary key,
  user_id       integer      not null references public.users (id) on delete cascade,
  business_name varchar(100) not null,
  phone         varchar(20),
  address       text,
  created_at    timestamp    not null default now()
);

create table if not exists public.quests (
  id          integer generated by default as identity primary key,
  title       varchar(100)   not null,
  description text,
  posted_by   integer        references public.users (id),
  deadline    date           not null,
  status      text           not null default 'open' check (status in ('open', 'in_progress', 'completed')),
  created_at  timestamp      not null default now(),
  reward      numeric(10, 2) not null default 0.00
);

create table if not exists public.quest_assignments (
  id            integer generated by default as identity primary key,
  -- One freelancer per quest.
  quest_id      integer      not null unique references public.quests (id) on delete cascade,
  freelancer_id integer      not null references public.users (id) on delete cascade,
  accepted_at   timestamp    not null default now(),
  status        text         not null default 'accepted' check (status in ('accepted', 'in_progress', 'completed')),
  proof_file    varchar(255)
);

-- MySQL compared usernames and emails case-insensitively; keep that so "Admin" and "admin" are the same account.
create unique index if not exists users_username_lower_idx on public.users (lower(username));
create unique index if not exists users_email_lower_idx    on public.users (lower(email));

create index if not exists freelancers_user_id_idx       on public.freelancers (user_id);
create index if not exists individual_clients_user_id_idx on public.individual_clients (user_id);
create index if not exists businesses_user_id_idx         on public.businesses (user_id);
create index if not exists quests_posted_by_idx           on public.quests (posted_by);
create index if not exists quest_assignments_freelancer_idx on public.quest_assignments (freelancer_id);

-- ---------------------------------------------------------------------------
-- Security
-- The website talks to the database directly over DATABASE_URL (as the
-- `postgres` role, which bypasses RLS). Turning RLS on with no policies
-- blocks Supabase's public REST API (anon / authenticated keys) from reading
-- these tables — so nobody can pull password hashes through it.
-- ---------------------------------------------------------------------------

alter table public.users              enable row level security;
alter table public.freelancers        enable row level security;
alter table public.individual_clients enable row level security;
alter table public.businesses         enable row level security;
alter table public.quests             enable row level security;
alter table public.quest_assignments  enable row level security;

